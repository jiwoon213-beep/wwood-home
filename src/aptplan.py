def ptype(area, year):
    old = bool(year) and year < 2005
    if area < 50: return "s40"
    if area < 66: return "o59" if old else "n59"
    if area < 80: return "n74"
    if area < 96: return "o84" if (bool(year) and year < 2008) else "n84"
    if area < 126: return "n100"
    return "l135"


def svg(key, E=lambda s: s):
    t, d, rooms, doors, marks = P[key]
    fill = {"b": BAL, "w": WET, "k": KIT}
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="Noto Sans KR,Apple SD Gothic Neo,Malgun Gothic,sans-serif">',
         f'<rect width="{W}" height="{H}" fill="#fff"/>']
    for x, y, w, h, nm, k in rooms:
        if not w: continue
        o.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill.get(k, FL)}" stroke="{WALL}" stroke-width="{3 if k == "b" else 7}"/>')
    for x, y, w, h, nm, k in rooms:
        if nm and w: o.append(f'<text x="{x + w / 2}" y="{y + h / 2 + 7}" text-anchor="middle" font-size="{20 if w > 140 else 16}" font-weight="700" fill="#6b6257">{E(nm)}</text>')
    for x, y, ori in doors:  # 문 자리: 벽을 지우고 여닫이 호
        if ori == "h":
            o.append(f'<line x1="{x - 32}" y1="{y}" x2="{x + 32}" y2="{y}" stroke="{FL}" stroke-width="10"/><path d="M{x - 32} {y} A64 64 0 0 1 {x + 32} {y - 56}" fill="none" stroke="#b9ad9b" stroke-width="2"/><line x1="{x - 32}" y1="{y}" x2="{x + 32}" y2="{y - 56}" stroke="#8a7f70" stroke-width="3"/>')
        else:
            o.append(f'<line x1="{x}" y1="{y - 32}" x2="{x}" y2="{y + 32}" stroke="{FL}" stroke-width="10"/><path d="M{x} {y - 32} A64 64 0 0 1 {x + 56} {y + 32}" fill="none" stroke="#b9ad9b" stroke-width="2"/><line x1="{x}" y1="{y - 32}" x2="{x + 56}" y2="{y + 32}" stroke="#8a7f70" stroke-width="3"/>')
    labs = [(x + w / 2, y + h / 2) for x, y, w, h, nm, k in rooms if nm and w]
    mk2 = []
    for n, x, y in marks:
        for lx, ly in labs:
            if abs(x - lx) < 70 and abs(y - ly) < 32: x = lx - 80 if x <= lx else lx + 80
        mk2.append((n, x, y))
    for n, x, y in mk2:
        o.append(f'<circle cx="{x}" cy="{y}" r="19" fill="#b06a2c" stroke="#fff" stroke-width="3"/><text x="{x}" y="{y + 7}" text-anchor="middle" font-size="20" font-weight="900" fill="#fff">{n}</text>')
    o.append(f'<text x="{W - 20}" y="{H - 8}" text-anchor="end" font-size="15" fill="#9a9086">예시 평면 · 실제 구조는 단지·세대마다 다름 · 영진종합목재 www.wwood.co.kr</text></svg>')
    return "".join(o)


def write(root):
    d = f"{root}/assets/apt"; os.makedirs(d, exist_ok=True)
    esc = lambda s: s.replace("&", "&amp;").replace("<", "&lt;")
    for k in P:
        s = svg(k, esc); p = f"{d}/plan-{k}.svg"
        if not os.path.exists(p) or open(p, encoding="utf-8").read() != s: open(p, "w", encoding="utf-8").write(s)


def legend(key, E):
    ns = [m[0] for m in P[key][4]]
    return '<ol class="apleg">' + "".join(f'<li value="{n}"><a href="{MK[n][1]}">{E(MK[n][0])}</a></li>' for n in sorted(set(ns))) + "</ol>"
